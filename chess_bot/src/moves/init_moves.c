static void generate_all_blocker_patterns(uint64_t movement_mask, int square, _list *blocker_buffer){
    _list *blocker_position_list = gl_create_list(sizeof(int));
    for (int i = 0; i < 64; i++){
        if ((movement_mask & (1UL << i)) != 0){
            gl_append_item(blocker_position_list, &i);
        }
    }

    int num_blocker_positions = gl_get_length(blocker_position_list);
    uint64_t none = 0;
    gl_append_item(blocker_buffer, &none);
    for (int i = 0; i < num_blocker_positions; i++){
        uint64_t blocker_position = 1UL << *(int *)gl_access_item(blocker_position_list, i);
        for (int j = gl_get_length(blocker_buffer) - 1; j >= 0; j--){
            uint64_t blocker_pattern = *(uint64_t *)gl_access_item(blocker_buffer, j) | blocker_position;
            gl_append_item(blocker_buffer, &blocker_pattern);
        }
    }

    gl_destroy_list(blocker_position_list);
}

static uint64_t generate_sliding_moves(int square, uint64_t blockers, _piece piece){
    // this is ugly
    // dont fix whats not broken i guess
    uint64_t moves = 0;
    if (piece == W_ROOK || piece == B_ROOK){
        uint64_t left_right = left_border | right_border, top_bottom = top_border | bottom_border;
        uint64_t check = 1UL << square;
        if ((square + 1) % 8 != 0){
            do{
                check <<= 1;
                moves |= check;
            } while((check & blockers) == 0 && (check & left_right) == 0);
        }
        if (square % 8 != 0){
            check = 1UL << square;
            do{
                check >>= 1;
                moves |= check;
            } while((check & blockers) == 0 && (check & left_right) == 0);
        }
        check = 1UL << square;
        do{
            check <<= 8;
            moves |= check;
        } while((check & blockers) == 0 && (check & top_bottom) == 0 && check != 0);
        check = 1UL << square;
        do{
            check >>= 8;
            moves |= check;
        } while((check & blockers) == 0 && (check & top_bottom) == 0 && check != 0);
    }
    else if (piece == W_BISHOP || piece == B_BISHOP){
        uint64_t check = 1UL << square;
        if (square % 8 != 0){
            do{
                check <<= 7;
                moves |= check;

            } while((check & blockers) == 0 && (check & perimeter) == 0 && check != 0);
            check = 1UL << square;
            do{
                check >>= 9;
                moves |= check;

            } while((check & blockers) == 0 && (check & perimeter) == 0 && check != 0);
        }
        if ((square + 1) % 8 != 0){
            check = 1UL << square;
            do{
                check <<= 9;
                moves |= check;
            } while((check & blockers) == 0 && (check & perimeter) == 0 && check != 0);
            check = 1UL << square;
            do{
                check >>= 7;
                moves |= check;
            } while((check & blockers) == 0 && (check & perimeter) == 0 && check != 0);

        }
    }

    return moves;
}

static void init_lookup_tables(){
    // init attack sets
    _list *blocker_patterns = gl_create_list(sizeof(uint64_t));
    for (int i = 0; i < 64; i++){
        // rook
        generate_all_blocker_patterns(rook_masks[i], i, blocker_patterns);
        for (int j = 0; j < gl_get_length(blocker_patterns); j++){
            uint64_t blockers = *(uint64_t *)gl_access_item(blocker_patterns, j);
            uint64_t index = (blockers * rook_magics[i]) >> rook_shifts[i];
            uint64_t moves = generate_sliding_moves(i, blockers, W_ROOK);
            rook_attacks[i][index] = moves;
        }

        gl_clear_list(blocker_patterns);

        // bishop
        generate_all_blocker_patterns(bishop_masks[i], i, blocker_patterns);
        for (int j = 0; j < gl_get_length(blocker_patterns); j++){
            uint64_t blockers = *(uint64_t *)gl_access_item(blocker_patterns, j);
            uint64_t index = (blockers * bishop_magics[i]) >> bishop_shifts[i];
            uint64_t moves = generate_sliding_moves(i, blockers, W_BISHOP);
            bishop_attacks[i][index] = moves;
        }

        gl_clear_list(blocker_patterns);

        // pawns
        int rank = i / 8;
        pawn_attacks[WHITE][i] = (5UL << i << 7) & (255UL << (8 * rank) << 8);
        pawn_attacks[BLACK][i] = (5UL << i >> 9) & (255UL << (8 * rank) >> 8);
        pawn_moves[WHITE][i] = (1UL << i << 8) | (rank == 1 ? 1UL << i << 16 : 0);
        pawn_moves[BLACK][i] = (1UL << i >> 8) | (rank == 6 ? 1UL << i >> 16 : 0);
    }

    gl_destroy_list(blocker_patterns);

    // compute rays
    for (int i = 0; i < 64; i++){
        int rank = i / 8, file = i % 8;
        int up = rank + 1, down = rank - 1, right = file + 1, left = file - 1;
        for (int j = 0; j < 7; j++){
            if (up < 8){
                // north, northeast, northwest
                rays[i][1] |= 1UL << (8 * up + file);
                rays[i][2] |= right < 8 ? 1UL << (8 * up + right) : 0;
                rays[i][0] |= left >= 0 ? 1UL << (8 * up + left) : 0;
            }
            if (down >= 0){
                // south, southeast, southwest
                rays[i][5] |= 1UL << (8 * down + file);
                rays[i][4] |= right < 8 ? 1UL << (8 * down + right) : 0;
                rays[i][6] |= left >= 0 ? 1UL << (8 * down + left) : 0;
            }
            // east, west
            rays[i][3] |= right < 8 ? 1UL << (8 * rank + right) : 0;
            rays[i][7] |= left >= 0 ? 1UL << (8 * rank + left) : 0;

            up++;
            down--;
            right++;
            left--;
        }
    }

    // castle moves
    castle_moves[WHITE][0] = 0;
    castle_moves[WHITE][1] = 1UL << 2;
    castle_moves[WHITE][2] = 1UL << 6;
    castle_moves[WHITE][3] = (1UL << 2) | (1UL << 6);
    castle_moves[BLACK][0] = 0;
    castle_moves[BLACK][1] = 1UL << 58;
    castle_moves[BLACK][2] = 1UL << 62;
    castle_moves[BLACK][3] = (1UL << 58) | (1UL << 62);
}

void mv_init_moves(){
    if (mv_ready == 1){
        return;
    }

    init_lookup_tables();
    mv_ready = 1;
}